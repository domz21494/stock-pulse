"use client";

import { useEffect, useState } from "react";
import { fmtPrice } from "@/lib/format";
import type { Insight, Sentiment, Tone } from "@/lib/insights/types";

const toneText: Record<Tone, string> = { up: "text-up", down: "text-down", neutral: "text-foreground" };
const sentimentStyle: Record<Sentiment, string> = {
  bullish: "text-up border-up/40 bg-up/10",
  bearish: "text-down border-down/40 bg-down/10",
  neutral: "text-amber-400 border-amber-400/40 bg-amber-400/10",
};

function Gauge({ score }: { score: number }) {
  const left = `${(score + 100) / 2}%`;
  return (
    <div className="space-y-1" aria-label={`Sentiment score ${score} out of 100`}>
      <div className="relative h-2 rounded-full bg-gradient-to-r from-down via-amber-400 to-up opacity-80">
        <div
          className="absolute top-1/2 h-4 w-4 -translate-x-1/2 -translate-y-1/2 rounded-full border-2 border-background bg-foreground shadow transition-[left] duration-700"
          style={{ left }}
        />
      </div>
      <div className="flex justify-between text-[10px] text-muted uppercase tracking-wide">
        <span>Bearish</span>
        <span>Neutral</span>
        <span>Bullish</span>
      </div>
    </div>
  );
}

function Levels({ support, resistance, price }: { support: number; resistance: number; price: number }) {
  const span = resistance - support || 1;
  const pos = Math.min(100, Math.max(0, ((price - support) / span) * 100));
  return (
    <div className="rounded-lg border border-border p-3 space-y-2">
      <p className="text-xs text-muted">20-day range · support → resistance</p>
      <div className="relative h-1.5 rounded-full bg-border">
        <div className="absolute inset-y-0 left-0 rounded-full bg-accent/50" style={{ width: `${pos}%` }} />
        <div className="absolute top-1/2 h-3 w-3 -translate-x-1/2 -translate-y-1/2 rounded-full bg-accent" style={{ left: `${pos}%` }} />
      </div>
      <div className="flex justify-between font-mono text-xs">
        <span className="text-down">${fmtPrice(support)}</span>
        <span className="text-muted">now ${fmtPrice(price)}</span>
        <span className="text-up">${fmtPrice(resistance)}</span>
      </div>
    </div>
  );
}

type PanelState = { key: string; insight?: Insight; error?: string };

async function fetchInsight(symbol: string, refresh: boolean, signal?: AbortSignal): Promise<PanelState | null> {
  try {
    const res = await fetch(`/api/insights?symbol=${symbol}${refresh ? "&refresh" : ""}`, { signal });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return { key: symbol, insight: await res.json() };
  } catch (e) {
    return (e as Error).name === "AbortError" ? null : { key: symbol, error: (e as Error).message };
  }
}

export default function InsightsPanel({ symbol, price }: { symbol: string; price?: number }) {
  const [state, setState] = useState<PanelState | null>(null);
  const [refreshing, setRefreshing] = useState(false);

  useEffect(() => {
    const ctrl = new AbortController();
    fetchInsight(symbol, false, ctrl.signal).then((r) => r && setState(r));
    return () => ctrl.abort();
  }, [symbol]);

  const current = state?.key === symbol ? state : null;
  const ins = current?.insight;

  return (
    <section className="rounded-lg border border-border bg-surface p-4 space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h2 className="font-semibold flex items-center gap-2">
          <span aria-hidden>✨</span> AI Insights
        </h2>
        <div className="flex items-center gap-3 text-xs text-muted">
          {ins && (
            <span title={ins.author === "ai" ? "Narrative written by AI from computed indicators" : "Generated by the built-in technical analysis engine"}>
              {ins.author === "ai" ? `AI · ${ins.model}` : "Built-in analysis engine"} ·{" "}
              {new Date(ins.generatedAt).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}
            </span>
          )}
          <button
            onClick={async () => {
              setRefreshing(true);
              const r = await fetchInsight(symbol, true);
              if (r) setState(r);
              setRefreshing(false);
            }}
            disabled={refreshing || !current}
            className="rounded-md border border-border px-2.5 py-1 hover:text-foreground disabled:opacity-40"
          >
            {refreshing ? "Analyzing…" : "↻ Refresh"}
          </button>
        </div>
      </div>

      {!current && (
        <div className="space-y-3 animate-pulse">
          <div className="h-2 rounded bg-border" />
          <div className="h-5 w-2/3 rounded bg-border" />
          <div className="h-16 rounded bg-border" />
        </div>
      )}
      {current?.error && <p className="text-sm text-down">Couldn&apos;t generate insights: {current.error}</p>}

      {ins && (
        <>
          <div className="grid gap-4 md:grid-cols-[1fr_auto] md:items-center">
            <Gauge score={ins.score} />
            <span className={`justify-self-start rounded-full border px-3 py-1 text-sm font-medium capitalize ${sentimentStyle[ins.sentiment]}`}>
              {ins.sentiment} · {ins.score > 0 ? "+" : ""}{ins.score}
            </span>
          </div>

          <div className="space-y-2">
            <h3 className="text-lg font-semibold leading-snug">{ins.headline}</h3>
            <p className="text-sm leading-relaxed text-foreground/85">{ins.summary}</p>
          </div>

          {ins.signals.length > 0 && (
            <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
              {ins.signals.map((s) => (
                <div key={s.label} className="rounded-lg border border-border p-3" title={s.detail}>
                  <p className="text-xs text-muted">{s.label}</p>
                  <p className={`font-mono text-sm font-medium ${toneText[s.tone]}`}>{s.value}</p>
                  <p className="mt-1 text-xs text-muted leading-snug">{s.detail}</p>
                </div>
              ))}
            </div>
          )}

          {ins.levels && <Levels {...ins.levels} price={price ?? (ins.levels.support + ins.levels.resistance) / 2} />}

          {ins.dataSource === "none" && (
            <p className="text-xs text-amber-400">Price history is unavailable right now, so this analysis uses today&apos;s quote only.</p>
          )}
          <p className="text-[11px] text-muted">
            Technical analysis of price data only — not financial advice.
            {ins.dataSource === "demo" && " Based on simulated demo prices."}
          </p>
        </>
      )}
    </section>
  );
}
